-- Vinted-Dashboard (Cloud) – Supabase/Postgres-Schema.
-- Erzeugt aus apps/api/src/db/pgSchema.ts – nicht von Hand ändern.
-- Die API legt das Schema beim Start selbst an (DB_AUTO_MIGRATE); alternativ im Supabase SQL-Editor ausführen.

-- ---------- helpers ----------
CREATE OR REPLACE FUNCTION app_uid() RETURNS text LANGUAGE sql STABLE AS $$ SELECT NULLIF(current_setting('app.user_id', true), '') $$;
CREATE OR REPLACE FUNCTION app_now() RETURNS text LANGUAGE sql STABLE AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

DO $$ BEGIN
  CREATE ROLE app_user NOLOGIN NOBYPASSRLS;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
-- The connecting role must be allowed to switch to app_user (SET LOCAL ROLE).
DO $$ BEGIN
  EXECUTE format('GRANT app_user TO %I', current_user);
EXCEPTION WHEN others THEN NULL; END $$;
GRANT USAGE ON SCHEMA public TO app_user;

-- ---------- SaaS: users, subscriptions, PC helper ----------
CREATE TABLE IF NOT EXISTS app_users (
  id TEXT PRIMARY KEY,                          -- Clerk user id (user_...)
  email TEXT,
  stripe_customer_id TEXT UNIQUE,
  stripe_subscription_id TEXT,
  subscription_status TEXT NOT NULL DEFAULT 'none', -- none | trialing | active | past_due | canceled | unpaid | incomplete
  current_period_end TEXT,
  cancel_at_period_end INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT app_now(),
  updated_at TEXT NOT NULL DEFAULT app_now()
);

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS terms_accepted_at TEXT;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS terms_version TEXT;

-- "Verträge hier kündigen" (§ 312k BGB): every request is kept as proof.
CREATE TABLE IF NOT EXISTS cancellation_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('ordentlich','ausserordentlich')),
  reason TEXT,
  effective TEXT,
  result TEXT,
  received_at TEXT NOT NULL DEFAULT app_now()
);
ALTER TABLE cancellation_requests ENABLE ROW LEVEL SECURITY; -- no policies: only the server (owner) reads it

CREATE TABLE IF NOT EXISTS helper_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_uid() REFERENCES app_users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,              -- sha256 of the token, the token itself is shown once
  last_seen_at TEXT,
  revoked_at TEXT,
  created_at TEXT NOT NULL DEFAULT app_now()
);

CREATE TABLE IF NOT EXISTS helper_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT app_uid(),
  kind TEXT NOT NULL,                           -- e.g. vinted.call, assist.start
  payload TEXT NOT NULL DEFAULT '{}',
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','running','done','failed','cancelled')),
  result TEXT,
  error TEXT,
  created_at TEXT NOT NULL DEFAULT app_now(),
  started_at TEXT,
  finished_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_helper_jobs_user_status ON helper_jobs(user_id, status, id);

-- ---------- app data (same columns as the local SQLite database) ----------
